public class Variables {
    public static void main(Strings[] args) {
        int a = 712;
        System.out.println(a);
        short b = 123;
        System.out.println(b);
        byte c = 127;// -128 127
        System.out.println(c);

        double d = 123.45;
        System.out.println(d);
        float f = 123.45F;
        System.out.println(f);

        char g  = 'a';
        System.out.println(g);

        boolean h = true;
        System.out.println(h);



    }
}
